"""Bundle the project modules into Kaggle's single-file Python entrypoint."""

from __future__ import annotations

import base64
import gzip
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parent
KERNEL_DIR = ROOT / "execution" / "kaggle_kernel"
SOURCE_FILES = [
    "download_data.py",
    "prepare_data.py",
    "train.py",
    "evaluate.py",
    "requirements.txt",
]
KERNEL_METADATA = {
    "id": "namlh2004/wmt25-esa-score-prediction-experiment",
    "title": "WMT25 ESA Score Prediction Experiment",
    "code_file": "main.py",
    "language": "python",
    "kernel_type": "script",
    "is_private": "true",
    "enable_gpu": "false",
    "enable_tpu": "false",
    "enable_internet": "true",
    "machine_shape": "",
    "dataset_sources": [],
    "competition_sources": [],
    "kernel_sources": [],
    "model_sources": [],
}


ENTRYPOINT_TEMPLATE = '''"""Self-contained Kaggle entrypoint generated by build_kaggle_kernel.py."""

from __future__ import annotations

import base64
import gzip
import importlib.util
import json
import subprocess
import sys
from pathlib import Path

BUNDLE_B64 = "__BUNDLE_B64__"
WORK_DIR = Path("/kaggle/working/wmt25-esa-score-experiment")
RAW_DATA = Path("/kaggle/temp/wmt25-genmt-humeval.jsonl")
DATA_DIR = WORK_DIR / "data" / "processed"
RESULTS_DIR = WORK_DIR / "results"
MODELS_DIR = WORK_DIR / "models"
SOURCE_DIR = Path("/kaggle/temp/wmt25-esa-source")


def materialize_sources() -> None:
    files = json.loads(gzip.decompress(base64.b64decode(BUNDLE_B64)))
    SOURCE_DIR.mkdir(parents=True, exist_ok=True)
    for name, content in files.items():
        (SOURCE_DIR / name).write_text(content, encoding="utf-8")


def run(script_name: str, *arguments: str) -> None:
    command = [sys.executable, str(SOURCE_DIR / script_name), *arguments]
    print("\\n$ " + " ".join(command), flush=True)
    subprocess.run(command, cwd=WORK_DIR, check=True)


def main() -> None:
    WORK_DIR.mkdir(parents=True, exist_ok=True)
    RAW_DATA.parent.mkdir(parents=True, exist_ok=True)
    materialize_sources()
    if importlib.util.find_spec("catboost") is None:
        subprocess.run(
            [sys.executable, "-m", "pip", "install", "-r", str(SOURCE_DIR / "requirements.txt")],
            check=True,
        )
    run("download_data.py", "--output", str(RAW_DATA))
    prepared = DATA_DIR / "annotations.csv.gz"
    run(
        "prepare_data.py",
        "--input", str(RAW_DATA),
        "--output-dir", str(DATA_DIR),
        "--results-dir", str(RESULTS_DIR),
    )
    run(
        "train.py",
        "--data", str(prepared),
        "--results-dir", str(RESULTS_DIR),
        "--models-dir", str(MODELS_DIR),
    )
    run(
        "evaluate.py",
        "--data", str(prepared),
        "--predictions", str(RESULTS_DIR / "predictions.csv.gz"),
        "--results-dir", str(RESULTS_DIR),
        "--models-dir", str(MODELS_DIR),
    )
    RAW_DATA.unlink(missing_ok=True)
    print(f"\\nExperiment complete. Outputs are under {WORK_DIR}.", flush=True)


if __name__ == "__main__":
    main()
'''


def build() -> None:
    bundle = {name: (ROOT / name).read_text(encoding="utf-8") for name in SOURCE_FILES}
    payload = json.dumps(bundle, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
    compressed = base64.b64encode(gzip.compress(payload, compresslevel=9)).decode("ascii")
    KERNEL_DIR.mkdir(parents=True, exist_ok=True)
    (KERNEL_DIR / "main.py").write_text(
        ENTRYPOINT_TEMPLATE.replace("__BUNDLE_B64__", compressed), encoding="utf-8"
    )
    (KERNEL_DIR / "kernel-metadata.json").write_text(
        json.dumps(KERNEL_METADATA, indent=2) + "\n", encoding="utf-8"
    )
    print(
        f"Built single-file Kaggle package at {KERNEL_DIR} "
        f"({(KERNEL_DIR / 'main.py').stat().st_size:,} bytes)"
    )


if __name__ == "__main__":
    build()
